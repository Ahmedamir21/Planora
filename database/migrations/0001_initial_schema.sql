-- Planora PostgreSQL foundation
-- Provider-neutral schema. Apply with a PostgreSQL owner/administration connection.
-- Published JSON files remain static repository references; runtime cutover is a later phase.

BEGIN;

CREATE SCHEMA IF NOT EXISTS planora;
REVOKE ALL ON SCHEMA planora FROM PUBLIC;

CREATE TABLE IF NOT EXISTS planora.semesters (
  semester_key text PRIMARY KEY,
  metadata jsonb NOT NULL CHECK (jsonb_typeof(metadata) = 'object'),
  is_active boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS semesters_one_active_idx
  ON planora.semesters (is_active) WHERE is_active = true;

-- Exact snapshots preserve the existing JSON/API contract while normalized tables are introduced.
CREATE TABLE IF NOT EXISTS planora.catalog_documents (
  semester_key text NOT NULL REFERENCES planora.semesters(semester_key) ON DELETE CASCADE,
  document_name text NOT NULL CHECK (document_name IN ('semester.json', 'courses.json', 'majors.json', 'sch.json')),
  state text NOT NULL CHECK (state IN ('published', 'draft')),
  content jsonb NOT NULL,
  content_sha256 char(64) NOT NULL CHECK (content_sha256 ~ '^[0-9a-f]{64}$'),
  revision integer NOT NULL DEFAULT 1 CHECK (revision > 0),
  updated_by text,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (semester_key, document_name, state)
);

CREATE TABLE IF NOT EXISTS planora.catalog_revisions (
  revision_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  semester_key text NOT NULL REFERENCES planora.semesters(semester_key) ON DELETE CASCADE,
  document_name text NOT NULL CHECK (document_name IN ('semester.json', 'courses.json', 'majors.json', 'sch.json')),
  revision integer NOT NULL CHECK (revision > 0),
  state text NOT NULL CHECK (state IN ('published', 'draft')),
  action text NOT NULL CHECK (action IN ('import', 'save_draft', 'publish', 'restore', 'sync_stage', 'sync_publish')),
  content jsonb NOT NULL,
  content_sha256 char(64) NOT NULL CHECK (content_sha256 ~ '^[0-9a-f]{64}$'),
  actor_id text,
  actor_name text,
  reason text,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (semester_key, document_name, state, revision)
);
CREATE INDEX IF NOT EXISTS catalog_revisions_recent_idx
  ON planora.catalog_revisions (semester_key, document_name, created_at DESC);

CREATE TABLE IF NOT EXISTS planora.courses (
  semester_key text NOT NULL REFERENCES planora.semesters(semester_key) ON DELETE CASCADE,
  catalog_type text NOT NULL CHECK (catalog_type IN ('courses', 'sch')),
  course_id text NOT NULL,
  code text NOT NULL,
  name text NOT NULL,
  category_code integer,
  credits numeric(4,1) NOT NULL DEFAULT 0 CHECK (credits >= 0),
  source_order integer NOT NULL CHECK (source_order >= 0),
  raw_payload jsonb NOT NULL CHECK (jsonb_typeof(raw_payload) = 'object'),
  PRIMARY KEY (semester_key, catalog_type, course_id)
);
CREATE INDEX IF NOT EXISTS courses_code_idx ON planora.courses (semester_key, code);

CREATE TABLE IF NOT EXISTS planora.instructors (
  instructor_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  semester_key text NOT NULL,
  catalog_type text NOT NULL,
  course_id text NOT NULL,
  instructor_order integer NOT NULL CHECK (instructor_order >= 0),
  name text NOT NULL,
  unassigned boolean NOT NULL DEFAULT false,
  raw_payload jsonb NOT NULL CHECK (jsonb_typeof(raw_payload) = 'object'),
  UNIQUE (semester_key, catalog_type, course_id, instructor_order),
  FOREIGN KEY (semester_key, catalog_type, course_id)
    REFERENCES planora.courses (semester_key, catalog_type, course_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS instructors_name_idx ON planora.instructors (semester_key, name);

CREATE TABLE IF NOT EXISTS planora.meetings (
  meeting_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instructor_id bigint NOT NULL REFERENCES planora.instructors(instructor_id) ON DELETE CASCADE,
  meeting_type text NOT NULL CHECK (meeting_type IN ('lecture', 'lab', 'tutorial')),
  section_code text NOT NULL DEFAULT '',
  day text NOT NULL DEFAULT '',
  start_minute integer NOT NULL CHECK (start_minute >= 0 AND start_minute < 1440),
  end_minute integer NOT NULL CHECK (end_minute > start_minute AND end_minute <= 1440),
  room text NOT NULL DEFAULT '',
  meeting_order integer NOT NULL CHECK (meeting_order >= 0),
  raw_payload jsonb NOT NULL CHECK (jsonb_typeof(raw_payload) = 'object'),
  UNIQUE (instructor_id, meeting_type, meeting_order)
);
CREATE INDEX IF NOT EXISTS meetings_day_time_idx ON planora.meetings (day, start_minute, end_minute);

CREATE TABLE IF NOT EXISTS planora.majors (
  semester_key text NOT NULL REFERENCES planora.semesters(semester_key) ON DELETE CASCADE,
  major_id text NOT NULL,
  title text NOT NULL,
  subtitle text NOT NULL DEFAULT '',
  blurb text NOT NULL DEFAULT '',
  source_order integer NOT NULL CHECK (source_order >= 0),
  raw_payload jsonb NOT NULL CHECK (jsonb_typeof(raw_payload) = 'object'),
  PRIMARY KEY (semester_key, major_id)
);

CREATE TABLE IF NOT EXISTS planora.major_years (
  semester_key text NOT NULL,
  major_id text NOT NULL,
  year_id text NOT NULL,
  label text NOT NULL,
  source_order integer NOT NULL CHECK (source_order >= 0),
  raw_payload jsonb NOT NULL CHECK (jsonb_typeof(raw_payload) = 'object'),
  PRIMARY KEY (semester_key, major_id, year_id),
  FOREIGN KEY (semester_key, major_id)
    REFERENCES planora.majors(semester_key, major_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS planora.major_year_courses (
  semester_key text NOT NULL,
  major_id text NOT NULL,
  year_id text NOT NULL,
  course_id text NOT NULL,
  source_order integer NOT NULL CHECK (source_order >= 0),
  PRIMARY KEY (semester_key, major_id, year_id, course_id),
  FOREIGN KEY (semester_key, major_id, year_id)
    REFERENCES planora.major_years(semester_key, major_id, year_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS major_year_courses_lookup_idx
  ON planora.major_year_courses (semester_key, course_id);

CREATE TABLE IF NOT EXISTS planora.admin_audit_events (
  event_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  actor_id text,
  actor_name text,
  action text NOT NULL,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS admin_audit_events_recent_idx
  ON planora.admin_audit_events (created_at DESC);

CREATE TABLE IF NOT EXISTS planora.sync_runs (
  run_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  source text NOT NULL,
  status text NOT NULL CHECK (status IN ('queued', 'running', 'validated', 'published', 'failed', 'rejected')),
  phase text NOT NULL DEFAULT 'queued',
  counts jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(counts) = 'object'),
  warnings jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(warnings) = 'array'),
  error_summary text,
  started_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz
);
CREATE INDEX IF NOT EXISTS sync_runs_recent_idx ON planora.sync_runs (started_at DESC);

COMMIT;
